#!/usr/bin/env python3
"""LaTeX macros and tables for the quantities in out/extras_v2.json.

Writes out/extras_v2.tex (one macro per value quoted in the text) and
out/table_cpu_energy.tex (processor-time and duty-cycle energy table) and
out/table_extras_runs.tex (per-run values of the derived quantities).
"""
from __future__ import annotations
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "out"
X = json.loads((OUT / "extras_v2.json").read_text())
N = json.loads((OUT / "numbers_v2.json").read_text())
C = {"native": "A", "matched": "B", "legacy": "C"}


def f(x, d):
    x = round(x, d) + 0.0          # no negative zero
    s = f"{abs(x):,.{d}f}".replace(",", "{,}")
    return ("\\textminus " + s) if x < 0 else s


def sgn(x, d):
    x = round(x, d) + 0.0
    return ("" if x < 0 else ("+" if x > 0 else "")) + f(x, d)


macros = {}


def m(name, val):
    macros[name] = val


cm, ef = X["conditions"], X["effects"]
for key, short, d in [("cpu_pct_background", "CPUbg", 2),
                      ("cpu_ms_background_per_inference", "CPUbgms", 2),
                      ("cpu_ms_workload_per_inference", "CPUwork", 1),
                      ("cpu_ms_call_upper_bound", "CPUcall", 1),
                      ("cpu_ms_outside_call_lower_bound", "CPUout", 1),
                      ("call_share_of_active_pct", "CallShare", 1),
                      ("inference_only_rate_per_s", "InfRate", 1),
                      ("frame_interval_ms_mean", "Gap", 1),
                      ("frame_interval_ms_p99", "Gapp", 0),
                      ("energy_active_J_per_cycle", "EactJ", 1),
                      ("energy_sleep_J_per_cycle", "EslpJ", 1),
                      ("energy_cycle_J", "EcycJ", 1),
                      ("sleep_share_of_cycle_energy_pct", "SlpShare", 1),
                      ("energy_sleep_mJ_per_inference", "EslpInf", 1),
                      ("energy_active_mJ_per_inference", "EactInf", 1),
                      ("inferences_per_cycle", "InfCyc", 0),
                      ("late_sleep_temp_c", "LateT", 1),
                      ("peak_slope_c_per_h", "Slope", 2)]:
    for c, L in C.items():
        m(f"{short}{L}", f(cm[c][key]["mean"], d))
    for e, tag in (("B_minus_A", "BA"), ("C_minus_B", "CB")):
        v = ef[key][e]
        m(f"{short}{tag}", sgn(v["mean"], d))
        m(f"{short}{tag}lo", f(v["ci95"][0], d))
        m(f"{short}{tag}hi", f(v["ci95"][1], d))

runs = X["runs"]
vals = lambda k: [r[k] for r in runs.values()]
m("SlopeMin", f(min(vals("peak_slope_c_per_h")), 2))
m("SlopeMax", f(max(vals("peak_slope_c_per_h")), 2))
m("CPUbgMaxPct", f(max(vals("cpu_pct_background")), 2))
m("CPUbgMaxMs", f(max(vals("cpu_ms_background_per_inference")), 1))
m("GapMaxPnn", f(max(vals("frame_interval_ms_p99")), 0))
d1 = [abs(r["peak_last20_c"] - r["peak_first20_c"]) for r in runs.values()]
m("DriftMax", f(max(d1), 1))
m("DriftMaxRun", max(runs, key=lambda l: abs(runs[l]["peak_last20_c"] - runs[l]["peak_first20_c"])).replace("_", "\\_"))
# block 2 thermal proxy
b2 = {r["condition"]: r for r in runs.values() if r["label"].endswith("_2")}
m("LateTBtwoCB", sgn(b2["legacy"]["late_sleep_temp_c"] - b2["matched"]["late_sleep_temp_c"], 1))
for b in (1, 3):
    bl = {r["condition"]: r for r in runs.values() if r["label"].endswith(f"_{b}")}
    m(f"LateTB{'one' if b == 1 else 'three'}CB", sgn(bl["legacy"]["late_sleep_temp_c"] - bl["matched"]["late_sleep_temp_c"], 1))

# two-block (camera pinned in every run) estimates of main quantities
tb = X["main_effects_blocks_2_3"]
for key, short, d in [("power_w_active", "Pact", 2), ("latency_ms_mean", "Lat", 2),
                      ("energy_per_inference_above_floor_mJ", "Einc", 1),
                      ("cpu_ms_per_inference", "CPUms", 1)]:
    for e, tag in (("B_minus_A", "BA"), ("C_minus_B", "CB")):
        v = tb[key][e]
        m(f"Two{short}{tag}", sgn(v["mean"], d))
        m(f"Two{short}{tag}pct", sgn(v["pct_of_base"], 1))
        m(f"Two{short}{tag}lo", f(v["ci95"][0], d))
        m(f"Two{short}{tag}hi", f(v["ci95"][1], d))
        m(f"Two{short}{tag}bTwo", sgn(v["per_block"][0], d))
        m(f"Two{short}{tag}bThree", sgn(v["per_block"][1], d))

# first-percentile latency before and after the image rebuild
R = N["runs"]
for l in ("matched_1", "matched_2", "matched_3", "legacy_1", "legacy_2", "legacy_3"):
    m("Pone" + l.replace("_", "").replace("1", "one").replace("2", "two").replace("3", "three"),
      f(R[l]["latency_ms_p01"], 1))

tex = "% generated by analysis/make_tex_extras.py from out/extras_v2.json\n"
tex += "".join(f"\\newcommand{{\\X{k}}}{{{v}}}\n" for k, v in macros.items())
(OUT / "extras_v2.tex").write_text(tex)

# ---------------------------------------------------------------- table
rows = [
    ("Processor time per inference", None, None),
    ("Total (ms)", "cpu_ms_per_inference", 1),
    ("Background (ms)", "cpu_ms_background_per_inference", 2),
    ("Workload (ms)", "cpu_ms_workload_per_inference", 1),
    ("In timed call, $\\leq$ (ms)", "cpu_ms_call_upper_bound", 1),
    ("Outside call, $\\geq$ (ms)", "cpu_ms_outside_call_lower_bound", 1),
    ("Timing of the active phase", None, None),
    ("Call share of active (\\%)", "call_share_of_active_pct", 1),
    ("Frame interval, mean (ms)", "frame_interval_ms_mean", 1),
    ("Call-only rate (s$^{-1}$)", "inference_only_rate_per_s", 1),
    ("Energy per duty cycle", None, None),
    ("Cycle duration (s)", "cycle_s", 2),
    ("Inferences per cycle", "inferences_per_cycle", 0),
    ("Active phase (J)", "energy_active_J_per_cycle", 1),
    ("Sleep phase (J)", "energy_sleep_J_per_cycle", 1),
    ("Whole cycle (J)", "energy_cycle_J", 1),
    ("Sleep share (\\%)", "sleep_share_of_cycle_energy_pct", 2),
    ("Active, per inference (mJ)", "energy_active_mJ_per_inference", 1),
    ("Sleep, per inference (mJ)", "energy_sleep_mJ_per_inference", 1),
]
lines = [r"\begin{table}[!t]", r"\centering",
         r"\caption{Processor time, active-phase timing and energy per duty cycle, derived from the existing logs. (a) Condition means ($\pm$ SD over three runs). (b) Within-block effects with 95\% confidence intervals ($t$, 2 d.f.); $^{\dagger}$: interval includes zero. Background is the 1\,Hz system-wide utilisation in the settled part of the sleep phase, expressed per inference. In timed call ($\leq$): upper bound, all four cores busy for the whole call; outside call ($\geq$): workload time minus that bound. Call-only rate: reciprocal of the mean call latency. The two phase energies per inference add up to the energy per inference over the cycle in Table~\ref{tab:results}.}",
         r"\label{tab:cpuenergy}", r"\setlength{\tabcolsep}{3pt}", r"\footnotesize",
         r"\resizebox{\textwidth}{!}{%", r"\begin{tabular}{lccc|cc}", r"\toprule",
         r" & \multicolumn{3}{c|}{(a) Condition means} & \multicolumn{2}{c}{(b) Effects [95\% CI]}\\",
         r"Quantity & A native & B matched & C legacy & $B-A$ & $C-B$\\", r"\midrule"]
for lab, key, d in rows:
    if key is None:
        lines.append(f"\\multicolumn{{6}}{{l}}{{\\emph{{{lab}}}}}\\\\")
        continue
    cells = [f"{f(cm[c][key]['mean'], d)}\\,$\\pm$\\,{f(cm[c][key]['sd'], d)}" for c in C]
    eff = []
    for e in ("B_minus_A", "C_minus_B"):
        v = ef[key][e]
        dag = "" if v["ci_excludes_zero"] else "$^{\\dagger}$"
        eff.append(f"{sgn(v['mean'], d)}{dag} {{\\scriptsize[{f(v['ci95'][0], d)}, {f(v['ci95'][1], d)}]}}")
    lines.append(f"{lab} & " + " & ".join(cells + eff) + r"\\[1pt]")
lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
(OUT / "table_cpu_energy.tex").write_text("\n".join(lines) + "\n")

# ---------------------------------------------------------------- per-run table
order = ["legacy_1", "matched_1", "native_1", "legacy_2", "native_2", "matched_2",
         "matched_3", "legacy_3", "native_3"]
lines = [r"\begin{table}[!ht]", r"\centering",
         r"\caption{Per-run values of the derived quantities. Background CPU: 1\,Hz utilisation in the settled sleep phase. Peak drift: least-squares slope of the cyclic peak temperature over the analysed period, and the mean of the last 20 analysed cycles minus that of the first 20. Late sleep: mean SoC temperature and fan speed in the last 3\,s of each sleep phase. p01: first percentile of inference latency.}",
         r"\label{tab:a-runs}", r"\setlength{\tabcolsep}{3pt}", r"\footnotesize",
         r"\resizebox{\textwidth}{!}{%", r"\begin{tabular}{llcccccccc}", r"\toprule",
         r" & & Backgr. & Outside call & Frame int. & \multicolumn{2}{c}{Peak drift} & \multicolumn{2}{c}{Late sleep} & \\",
         r"\cmidrule(lr){6-7}\cmidrule(lr){8-9}",
         r"Block & Run & CPU (\%) & $\geq$ (ms) & p99 (ms) & ($^\circ$C/h) & (last$-$first, $^\circ$C) & ($^\circ$C) & (rpm) & p01 (ms)\\",
         r"\midrule"]
for i, l in enumerate(order):
    r, n = runs[l], R[l]
    lines.append(f"{i // 3 + 1} & \\texttt{{{l.replace('_', '{\\_}')}}} & {f(r['cpu_pct_background'], 2)} & "
                 f"{f(r['cpu_ms_outside_call_lower_bound'], 1)} & {f(r['frame_interval_ms_p99'], 0)} & "
                 f"{sgn(r['peak_slope_c_per_h'], 2)} & {sgn(r['peak_last20_c'] - r['peak_first20_c'], 1)} & "
                 f"{f(r['late_sleep_temp_c'], 1)} & {f(r['late_sleep_fan_rpm'], 0)} & {f(n['latency_ms_p01'], 1)}\\\\")
    if i in (2, 5):
        lines.append(r"\addlinespace")
lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
(OUT / "table_extras_runs.tex").write_text("\n".join(lines) + "\n")
print("wrote out/extras_v2.tex, out/table_cpu_energy.tex, out/table_extras_runs.tex")
